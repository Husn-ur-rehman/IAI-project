"""Calibration: set "abnormal" from the normal population only.

1. Write all base facts to Prolog and query the KB's own metric definitions (value/3).
2. Keep only players from the CALIBRATION half of the matches with no cheater present
   (even-numbered `no_cheater_present` files). The odd half is held out for evaluation, so the
   false-positive rate is measured on players the thresholds never saw.
   Clean players inside cheater matches are excluded too, because cheaters distort their stats.
3. Take the 95th and 99th percentile of each metric -> kb/thresholds.pl.

No cheater statistics are used to set thresholds.

Why only p95/p99:
- The "no cheater" matches contain unlabelled cheaters. You can see it in the jump from p95 to p99
  (headshot_rate 0.36 -> 0.71, wallbang_rate 0.20 -> 0.78), so p99.9 is unusable.
- Tukey IQR fences were rejected because metrics where most players score zero
  (air/blind kill rate) have IQR = 0, which gives a threshold of 0.
- Mode-specific thresholds were rejected because Official and Premier differ mainly in how
  contaminated they are, not in normal play, and per-mode samples are small.

Usage: python -m cheatdetect.calibrate
"""
from __future__ import annotations

from datetime import date

import pandas as pd

from cheatdetect import config, prolog_io

PERCENTILES = {"p95": 0.95, "p99": 0.99}


def is_calibration_match(match_id: str) -> bool:
    """Even-numbered clean matches calibrate; everything else is used for evaluation."""
    m = str(match_id)
    return m.startswith("n") and int(m[1:]) % 2 == 0


def metric_values() -> pd.DataFrame:
    """All (pid, metric, value) triples the KB can derive, with match context."""
    players = pd.read_parquet(config.PLAYERS_FILE)
    kills = pd.read_parquet(config.KILLS_FILE)
    prolog_io.write_facts(players, kills)
    prolog_io.reload_kb()
    prolog_io.load_facts()

    rows = [(r["P"], r["M"], float(r["V"])) for r in prolog_io.engine().query("value(P, M, V)")]
    values = pd.DataFrame(rows, columns=["pid", "metric", "value"])
    return values.merge(players[["pid", "match_id", "mode"]], on="pid")


def compute_thresholds(values: pd.DataFrame) -> pd.DataFrame:
    clean = values[values.match_id.map(is_calibration_match).astype(bool)]
    out = clean.groupby("metric")["value"].quantile(list(PERCENTILES.values())).unstack()
    out.columns = list(PERCENTILES)
    out["n_players"] = clean.groupby("metric").size()
    return out


def write_thresholds(t: pd.DataFrame):
    lines = [
        "% GENERATED by cheatdetect.calibrate. Do not edit by hand.",
        f"% {date.today()}: percentiles of each metric over the calibration half (even ids) of no-cheater matches.",
        "% threshold(Metric, Percentile, Value).",
        "",
    ]
    for metric, r in t.iterrows():
        lines.append(f"% {metric}: n={int(r.n_players)}")
        for p in PERCENTILES:
            lines.append(f"threshold({metric}, {p}, {r[p]:.4f}).")
    config.THRESHOLDS_FILE.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main():
    values = metric_values()
    thresholds = compute_thresholds(values)
    write_thresholds(thresholds)

    config.REPORTS_DIR.mkdir(exist_ok=True)
    thresholds.to_csv(config.REPORTS_DIR / "calibration_thresholds.csv")
    clean = values[values.match_id.map(is_calibration_match).astype(bool)]
    by_mode = clean.groupby(["metric", "mode"], observed=True)["value"].quantile(0.99).unstack()
    by_mode.to_csv(config.REPORTS_DIR / "calibration_p99_by_mode.csv")

    pd.set_option("display.width", 160)
    print(thresholds.round(3))
    print("\np99 by match mode (does mode need separate thresholds?):")
    print(by_mode.round(3))
    print(f"\nwrote {config.THRESHOLDS_FILE}")


if __name__ == "__main__":
    main()
